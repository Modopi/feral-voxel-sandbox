const GENERIC = '지금은 할 수 없습니다. 상황을 확인하고 다시 시도하세요.';
const STALE = '대상을 찾지 못했습니다. 목록을 다시 확인하세요.';
const PROCESSED = '이미 처리된 요청입니다.';

/** Text for a failure code or an already human-readable reason. */
export function reasonText(reason) {
 if (reason == null || reason === '') return GENERIC;
 const text = String(reason);
 if (REASON_TEXT[text]) return REASON_TEXT[text];
 if (!/^[a-z][a-z0-9_]*$/.test(text)) return text;
 if (text.startsWith('unknown_') || text.startsWith('wrong_')) return STALE;
 if (text.endsWith('_conflict') || text.endsWith('_already_used')) return PROCESSED;
 return GENERIC;
}

/** True when a code has wording beyond the generic fallback; used by regression tests. */
export function isTranslated(reason) {
 const text = String(reason);
 return !!REASON_TEXT[text] || text.startsWith('unknown_') || text.startsWith('wrong_') || text.endsWith('_conflict') || text.endsWith('_already_used') || /^(invalid|unsupported)_/.test(text) || ['claim_required','progression_required','migration_context_required','fragment_mass_allocation_required','fragment_snapshot_mismatch','mass_not_conserved'].includes(text);
}
