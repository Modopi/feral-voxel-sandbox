import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { auditDesign } from './audit-content-design.mjs';
import { assertAuthoringInvariant } from './asset-pipeline/authoring.mjs';
import { validateAsset } from './asset-pipeline/model.mjs';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const DOCUMENTS = ['environments', 'blocks', 'creatures', 'structures', 'bosses', 'progression'];
const CATEGORIES = ['creature', 'boss', 'structure', 'environment', 'equipment'];
const EQUIPMENT_ASSET_KINDS = ['tool', 'station', 'component', 'gear_baseline', 'weapon_pattern'];
const HELPERS = ['authoring', 'model', 'solid', 'physics'];
const HEADER = '// Generated by tools/build-runtime-content.mjs. Edit canonical design/tool sources, then rebuild.\n';
const FREEZE = 'function freeze(value) { if (value && typeof value === "object" && !Object.isFrozen(value)) { for (const child of Object.values(value)) freeze(child); Object.freeze(value); } return value; }\n';
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const ensure = (value, message) => { if (!value) throw new Error(message); };

export async function compileRuntimeContent(sourceRoot = ROOT) {
  const audit = auditDesign(path.join(sourceRoot, 'design/content'));
  ensure(audit.valid, `Content audit failed: ${audit.errors.join('; ')}`);
  const content = Object.fromEntries(await Promise.all(DOCUMENTS.map(async name => [name,
    JSON.parse(await fs.readFile(path.join(sourceRoot, `design/content/${name}.json`), 'utf8'))])));
  const manifest = JSON.parse(await fs.readFile(path.join(sourceRoot, 'design/assets/manifest.json'), 'utf8'));
  const library = new Map();
  for (const entry of manifest.entries) {
    ensure(/^[a-z0-9_-]+$/.test(entry.id) && CATEGORIES.includes(entry.category), 'Invalid asset identity');
    ensure(entry.model === `models/${entry.id}.voxel.json`, `Unexpected model path: ${entry.id}`);
    ensure(!library.has(entry.id), `Duplicate asset: ${entry.id}`);
    const bytes = await fs.readFile(path.join(sourceRoot, 'design/assets', entry.model));
    ensure(hash(bytes) === entry.sha256, `Canonical model hash mismatch: ${entry.id}`);
    const model = JSON.parse(bytes);
    ensure(model.id === entry.id && model.category === entry.category, `Asset identity mismatch: ${entry.id}`);
    assertAuthoringInvariant(model);
    library.set(entry.id, model);
  }
  for (const entry of manifest.entries) {
    const model = library.get(entry.id), stats = validateAsset(model, library, content);
    ensure(JSON.stringify(model.contentRef) === JSON.stringify(entry.contentRef), `Content reference mismatch: ${entry.id}`);
    for (const key of ['boxes', 'parts', 'anchors', 'bounds']) ensure(JSON.stringify(stats[key]) === JSON.stringify(entry[key]), `Manifest ${key} mismatch: ${entry.id}`);
  }
  for (const [document, category] of [['creatures','creature'],['bosses','boss'],['structures','structure'],['environments','environment'],['progression','equipment']]) {
    const expected = new Set(content[document].entries.filter(e => category !== 'equipment' || EQUIPMENT_ASSET_KINDS.includes(e.kind)).map(e => e.id));
    for (const model of library.values()) if (model.category === category) ensure(expected.delete(model.id), `Unexpected ${category}: ${model.id}`);
    ensure(!expected.size, `Missing ${category} assets: ${[...expected].join(', ')}`);
  }
  const files = new Map();
  files.set('catalog.generated.js', HEADER + FREEZE + `export const CONTENT = freeze(${JSON.stringify(content)});\n`);
  for (const category of CATEGORIES) {
    const models = Object.fromEntries([...library].filter(([, model]) => model.category === category));
    files.set(`models/${category}.generated.js`, HEADER + FREEZE + `export const MODELS = freeze(${JSON.stringify(models)});\n`);
  }
  const loaders = CATEGORIES.map(category => `  ${category}: () => import('./models/${category}.generated.js'),`).join('\n');
  files.set('assets.generated.js', HEADER + FREEZE + `export const ASSETS = freeze(${JSON.stringify(Object.fromEntries(manifest.entries.map(entry => [entry.id, entry])))});\n` +
`const loaders = {\n${loaders}\n};
const chunks = new Map();
export async function loadAsset(id) {
  if (!Object.hasOwn(ASSETS, id)) throw new Error('Unknown asset: ' + id);
  const category = ASSETS[id].category;
  if (!chunks.has(category)) chunks.set(category, loaders[category]().catch(error => { chunks.delete(category); throw error; }));
  return (await chunks.get(category)).MODELS[id];
}
export async function loadAssetLibrary(id) {
  const library = new Map();
  async function visit(assetId) {
    if (library.has(assetId)) return;
    const model = await loadAsset(assetId);
    library.set(assetId, model);
    for (const instance of model.instances) await visit(instance.assetId);
  }
  await visit(id);
  return library;
}
`);
  for (const helper of HELPERS) {
    const source = await fs.readFile(path.join(sourceRoot, `tools/asset-pipeline/${helper}.mjs`), 'utf8');
    ensure(!/\b(?:process|Buffer)\.|\brequire\s*\(|['"]node:/.test(source), `Node-only dependency in ${helper}`);
    const imports = [...source.matchAll(/\b(?:from\s*|import\s*\(?\s*)['"]([^'"]+)['"]/g)].map(match => match[1]);
    for (const specifier of imports) ensure(HELPERS.some(name => specifier === `./${name}.mjs`), `Unpackaged dependency ${helper}: ${specifier}`);
    files.set(`voxel/${helper}.mjs`, source);
  }
  return { files, assetCount: library.size, counts: audit.counts };
}

export async function buildRuntimeContent({ sourceRoot = ROOT, outputDirectory = path.join(sourceRoot, 'app/src/main/assets/content-runtime'), check = false } = {}) {
  // Validate everything before any write: invalid sources cannot partially replace a package.
  const { files, assetCount, counts } = await compileRuntimeContent(sourceRoot);
  for (const [relative, source] of files) {
    const target = path.join(outputDirectory, relative);
    if (check) {
      const actual = await fs.readFile(target);
      ensure(actual.equals(Buffer.from(source)), `Stale runtime package: ${relative}; run node tools/build-runtime-content.mjs`);
    } else {
      await fs.mkdir(path.dirname(target), { recursive: true });
      await fs.writeFile(target, source);
    }
  }
  for (const folder of ['models', 'voxel']) {
    const names = await fs.readdir(path.join(outputDirectory, folder));
    for (const name of names) if (!files.has(`${folder}/${name}`)) throw new Error(`Unexpected generated runtime file: ${folder}/${name}`);
  }
  return { valid: true, mode: check ? 'check' : 'build', assetCount, counts, generatedFiles: files.size,
    generatedBytes: [...files.values()].reduce((sum, source) => sum + Buffer.byteLength(source), 0), modelChunks: CATEGORIES.length };
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { console.log(JSON.stringify(await buildRuntimeContent({ check: process.argv.includes('--check') }), null, 2)); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
